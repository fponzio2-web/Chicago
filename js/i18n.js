const LANG_KEY = 'chicago-lang';
let LANG = 'pt';
try { const saved = localStorage.getItem(LANG_KEY); if (saved === 'en' || saved === 'pt') LANG = saved; } catch (e) { /* ignora */ }

function tr(key, vars) {
  let s = (STRINGS[LANG] && STRINGS[LANG][key] != null) ? STRINGS[LANG][key] : (STRINGS.pt[key] != null ? STRINGS.pt[key] : key);
  if (vars) Object.keys(vars).forEach(k => { s = s.split('{' + k + '}').join(vars[k]); });
  return s;
}
// Rótulo traduzido de uma categoria; o VALOR salvo no item/banco continua sempre em português.
const CAT_SLUG_FOR_LABEL = { 'Atração': 'catAtracao', 'Museu': 'catMuseu', 'Parque': 'catParque', 'Restaurante': 'catRestaurante',
  'Fast food': 'catFastfood', 'Bar / Café': 'catBarcafe', 'Compras': 'catCompras', 'Evento': 'catEvento', 'Outro': 'catOutro' };
function categoryLabel(cat) { return cat ? tr(CAT_SLUG_FOR_LABEL[cat] || cat) : tr('noCategory'); }

function applyI18n() {
  document.documentElement.lang = LANG === 'en' ? 'en' : 'pt-BR';
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = tr(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = tr(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', tr(el.dataset.i18nAria)); });
  const langBadge = document.getElementById('langBadge');
  if (langBadge) langBadge.textContent = LANG === 'en' ? 'EN' : 'PT';
}
function setLang(lang) {
  LANG = lang === 'en' ? 'en' : 'pt';
  try { localStorage.setItem(LANG_KEY, LANG); } catch (e) { /* ignora */ }
  applyI18n();
  if (typeof render === 'function') render();
}
